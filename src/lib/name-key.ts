/**
 * 사람 이름 두 개가 **같은 사람인가**를 가르는 열쇠. 이 앱에 이 규칙은 여기 하나뿐이다.
 *
 * ## 왜 한 곳인가
 *
 * 예전에는 두 벌이었다. 목록 중복 거르기(`dedupeRoster`)와 입력 칸(`roster-input.tsx`)은
 * "앞뒤 공백을 뗀 뒤 글자가 똑같은가" 였고, 에이전트 이름을 거르는 닫힌 집합
 * (`recording-server.ts`)은 "유니코드 정규화 + 소문자" 였다. 그 틈에서:
 *
 * - `["Alpha", "alpha"]` · NFC/NFD 로 적힌 `"지훈"` 둘이 **두 명**으로 세어져 `k` 가 하나
 *   커졌다 (맥의 입력기와 복사해 붙인 글이 서로 다른 조합형을 낸다).
 * - 목록 `["Kim", "kim"]` 은 목록 쪽에서 두 명, 닫힌 집합 쪽에서 한 명이었다. 같은 목록이
 *   어느 입구로 읽히느냐에 따라 사람 수가 달랐다.
 *
 * 입구마다 규칙이 다르면 어느 입구로 들어왔느냐에 따라 사람 수가 달라진다. 그래서
 * 목록 거르기 · 입력 칸 · 닫힌 집합이 모두 이 함수 하나를 부른다.
 *
 * **이 열쇠가 막지 않는 것:** 에이전트가 목록의 같은 이름을 **두 군집에** 붙이는 것.
 * 한 사람의 목소리가 두 군집으로 과분할되면 두 군집에 같은 이름이 붙는 것이 옳은 답이라,
 * 제품 결정으로 막지 않는다. 이 열쇠는 "몇 명인가" 와 "목록의 어느 이름인가" 만 가른다.
 *
 * ## 무엇을 같다고 보나
 *
 * - **NFKC** — 조합형 차이(NFC/NFD)와 전각 글자(`Ｋｉｍ`)를 한 모양으로. 이름에서
 *   전각 `Ｋｉｍ` 과 `Kim` 을 다른 사람으로 볼 까닭이 없다.
 * - **보이지 않는 형식 문자(유니코드 Cf)** — 지운다. 폭 없는 공백(U+200B) · 폭 없는
 *   결합자(U+200D) · 단어 결합자(U+2060) · 소프트 하이픈(U+00AD) 같은 것이다. 슬랙·노션에서
 *   복사해 붙인 이름에 흔히 묻어 오고, 화면에서는 안 보인다. 안 지우면 눈에 똑같은
 *   `Kim` 과 `Kim`+U+200B 가 두 명으로 세어져 `k` 가 커지고, 에이전트가 보낸 `Kim` 은
 *   목록에 없는 이름으로 버려진다. 형식 문자만으로 된 "이름" 은 지우고 나면 비므로
 *   이름이 아니다 (`dedupeNames` 가 버리고, `roster-schema.ts` 가 거절한다).
 * - 공백 — 앞뒤를 떼고 안쪽 연속 공백은 하나로. `"Kim  Lee"` 는 손이 미끄러진 것이다.
 * - 대소문자 — `toLowerCase()`. **`toLocaleLowerCase()` 가 아니다** — 이 함수는 서버와
 *   브라우저 양쪽에서 돌고, 둘의 로캘이 다르면(터키어의 I 처럼) 같은 이름이 한쪽에서만
 *   같다고 나온다.
 *
 * 열쇠는 비교에만 쓴다. **화면에 보이는 철자는 사람이 처음 적은 것**이다 — 다만 형식
 * 문자는 보이는 철자에서도 뗀다 (`cleanName`). 남겨 두면 저장된 이름끼리 글자 비교가
 * 어긋나고, 어차피 사람 눈에는 없는 글자다.
 *
 * 이 파일은 의존성이 없다 — 입력 칸(브라우저)이 부르므로 zod 나 DB 를 끌고 오면 안 된다.
 */
export function nameKey(v: string): string {
  return cleanName(v.normalize("NFKC")).replace(/\s+/gu, " ").trim().toLowerCase();
}

/** 보이지 않는 형식 문자(유니코드 일반 범주 Cf). `nameKey` 의 설명. */
const FORMAT_CHARS = /\p{Cf}/gu;

/**
 * **보여 줄 철자**를 다듬는다 — 형식 문자를 떼고 앞뒤 공백을 뗀다. 그 밖(대소문자·조합형·
 * 안쪽 공백)은 사람이 적은 그대로 둔다. 비면 이름이 아니다.
 */
export function cleanName(v: string): string {
  return v.replace(FORMAT_CHARS, "").trim();
}

/**
 * 같은 사람을 두 번 적은 것은 **한 명으로 센다.** 먼저 적은 철자가 남고 순서는 적은 그대로다.
 *
 * 두 번 세면 `k` 가 하나 커지는데, 그건 사람이 뜻한 바가 아니라 손이 미끄러진 것이다.
 */
export function dedupeNames(names: readonly string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of names) {
    const name = cleanName(raw);
    const key = nameKey(name);
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(name);
  }
  return out;
}
